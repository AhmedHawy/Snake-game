const TABLES: Record<Lang, Record<I18nKey, string>> = { en, ar };

let current: Lang = 'ar';

export function setLang(lang: Lang): void {
  current = lang;
}

export function getLang(): Lang {
  return current;
}

export function t(key: I18nKey, vars?: Record<string, string | number>): string {
  let s = TABLES[current][key] ?? en[key] ?? key;
  if (vars) for (const k in vars) s = s.replace(`{${k}}`, formatNum(vars[k]));
  return s;
}

/** Numbers use Western digits in both languages for readability in the HUD. */
export function formatNum(v: string | number): string {
  return typeof v === 'number' ? String(v) : v;
}
